import mongoose from "mongoose";

const messageSchema = new mongoose.Schema(
  {
    conversationId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Conversation",
      required: true,
      index: true, // Frequent query: "all messages in a conversation"
    },
    role: {
      type: String,
      enum: ["user", "assistant"],
      required: true,
    },
    content: {
      type: String,
      required: true,
    },
    /**
     * The agent that generated this response (e.g., 'search', 'chat', 'coding', etc.).
     * Used by router to maintain agent continuity on follow-up messages.
     */
    agentType: {
      type: String,
      default: null,
    },
    /**
     * Images from Tavily search results — only populated for assistant
     * messages generated by the search agent. Empty array for all other messages.
     * Stored alongside the message so images persist and display correctly
     * on page refresh (not just in the initial optimistic response).
     */
    searchImages: {
      type: [
        {
          url: { type: String, required: true },
          description: { type: String, default: "" },
        },
      ],
      default: [],
    },
  },
  {
    timestamps: true, // Adds createdAt automatically
  }
);

const Message = mongoose.model("Message", messageSchema);

export default Message;
